export function t(key,values={}){let text=locale==='ru'?key:strings[key]?.[locale==='zh'?1:0]??key;return text.replace(/\{(\w+)\}/g,(_,key)=>values[key]??`{${key}}`);}
export function localizeShell(){
 document.documentElement.lang=locale==='zh'?'zh-CN':locale;
 const walker=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);const nodes=[];while(walker.nextNode())nodes.push(walker.currentNode);
 for(const node of nodes){if(node.parentElement.closest('script,style'))continue;const source=node.textContent.trim();if(strings[source])node.textContent=node.textContent.replace(source,t(source));}
 for(const element of document.querySelectorAll('[title],[aria-label],[placeholder]'))for(const attribute of ['title','aria-label','placeholder']){const source=element.getAttribute(attribute);if(source&&strings[source])element.setAttribute(attribute,t(source));}
 const select=document.getElementById('language');select.value=locale;select.onchange=()=>{try{localStorage.setItem('ekza-assets-language',select.value);}catch{}location.reload();};
}
